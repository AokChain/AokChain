"""Generate src/bip39_wordlists.h from the BIP39 word lists.

usage: gen_bip39_wordlists.py english.txt korean.txt > src/bip39_wordlists.h

The lists are the ones published with BIP39
(https://github.com/bitcoin/bips/tree/master/bip-0039). Words are written in
NFKD, the form BIP39 hashes, as UTF-8 byte escapes.
"""
import hashlib
import sys
import unicodedata

EXPECTED = {
    "english": "2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda",
    "korean": "9e95f86c167de88f450f0aaf89e87f6624a57f973c67b516e338e8e8b8897f60",
}

print("// Generated by contrib/aokchain/gen_bip39_wordlists.py. Do not edit.")
print("#ifndef AOKCHAIN_BIP39_WORDLISTS_H")
print("#define AOKCHAIN_BIP39_WORDLISTS_H")
for path in sys.argv[1:]:
    name = path.split("/")[-1].split(".")[0]
    data = open(path, "rb").read()
    assert hashlib.sha256(data).hexdigest() == EXPECTED[name], "unexpected word list: " + path
    words = data.decode("utf8").split()
    assert len(words) == 2048
    print("\n// sha256 of the source list: %s" % EXPECTED[name])
    print("static const char* const bip39_wordlist_%s[2048] = {" % name)
    for w in words:
        b = unicodedata.normalize("NFKD", w).encode("utf8")
        lit = b.decode("ascii") if all(c < 128 for c in b) else "".join("\\x%02x" % c for c in b)
        print('    "%s",' % lit)
    print("};")
print("\n#endif // AOKCHAIN_BIP39_WORDLISTS_H")
